"""Forbes-specific markdown extraction helpers."""

from __future__ import annotations

import re
from urllib.parse import urlparse

FORBES_SHELL_MARKERS = (
    "today's highlights",
    "subscribe to the daily newsletter",
    "games",
    "my account notifications",
    "get custom alerts with member perks",
    "join the conversation",
    "comments",
    "loading video player",
    "forbes’ featured video",
    "newsletters",
    "become a forbes member",
    "premium",
    "want to save more articles? subscribe today.",
)
FORBES_SKIP_LINE_MARKERS = (
    "promoted",
    "follow author",
    "0",
    "--:-- / --:--",
    "this voice experience is generated by ai.[learn more](https://www.forbes.com/sites/forbesdigitalgroup/article/forbes-ai-audio-learn-more/).",
)
FORBES_END_SECTION_MARKERS = (
    "## join the conversation",
    "comments",
    "loading video player",
    "forbes’ featured video",
    "newsletters",
    "become a forbes member",
    "premium",
)


def extract_forbes_article_markdown(content: str, *, source: str) -> str | None:
    """Return the article body from noisy Forbes markdown when available."""
    if _normalize_host(source) != "forbes.com":
        return None

    lines = [line.rstrip() for line in content.splitlines()]
    if not lines:
        return None

    title_index = next(
        (idx for idx, line in enumerate(lines) if line.strip().startswith("# ")),
        None,
    )
    if title_index is None:
        return None

    article_lines = lines[title_index:]
    cleaned_lines: list[str] = []
    paragraph_started = False

    for raw_line in article_lines:
        line = raw_line.strip()
        if not line:
            if cleaned_lines and cleaned_lines[-1]:
                cleaned_lines.append("")
            continue

        lowered = line.lower()
        if any(lowered.startswith(marker) for marker in FORBES_END_SECTION_MARKERS):
            break
        if any(marker == lowered for marker in FORBES_SKIP_LINE_MARKERS):
            continue
        if any(marker == lowered for marker in FORBES_SHELL_MARKERS):
            continue
        if line.startswith("[Editorial Standards]"):
            break
        if line.startswith("![Image 21](") or "t.co/i/adsct" in line:
            continue
        if line.startswith("The Prompt: Get the week’s biggest AI news"):
            continue
        if line.startswith("[Explore More Newsletters]"):
            continue
        if line.startswith("1/1 Skip Ad Continue watching after the ad"):
            continue
        if line.startswith("Visit Advertiser website") or line.startswith(
            "[GO TO PAGE]"
        ):
            continue
        if line.startswith("More importantly,"):
            paragraph_started = True
            cleaned_lines.append(line)
            continue
        if line.startswith("MORE FOR YOU"):
            continue
        if line.startswith("### [") and "](" in line:
            continue
        if line.startswith("By[") or line.startswith("By ["):
            cleaned_lines.append(_normalize_forbes_byline(line))
            continue
        if line.startswith("Senior Contributor.") or line.startswith(
            "Forbes contributors publish"
        ):
            cleaned_lines.append(line)
            continue
        if re.match(r"^[A-Z][a-z]{2} \d{1,2}, \d{4},", line):
            cleaned_lines.append(line)
            continue
        if line.startswith("!["):
            cleaned_lines.append(line)
            continue
        if (
            paragraph_started
            and len(line.split()) < 6
            and not line.startswith(("*", "-", "#"))
            and "](" not in line
        ):
            continue

        if len(line.split()) >= 12:
            paragraph_started = True
        if paragraph_started or line.startswith(("# ", "*", "-")):
            cleaned_lines.append(line)

    article = "\n".join(cleaned_lines).strip()
    if not article:
        return None
    return re.sub(r"\n{3,}", "\n\n", article).strip()


def _normalize_host(url: str) -> str:
    host = urlparse(url).netloc.lower().strip(".")
    if host.startswith("www."):
        host = host[4:]
    return host


def _normalize_forbes_byline(line: str) -> str:
    if line.startswith("By ["):
        return line
    if line.startswith("By["):
        return re.sub(r"^By\[([^\]]+)\]\([^)]+\),?$", r"By [\1]", line)
    return line
