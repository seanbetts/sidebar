#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');

const sourcePath = path.join(repoRoot, 'shared', 'marketingCopy.json');
const tsPath = path.join(repoRoot, 'shared', 'marketingCopy.ts');
const swiftPath = path.join(repoRoot, 'ios', 'sideBar', 'sideBarShared', 'Utilities', 'MarketingCopy.swift');

const mode = process.argv.includes('--check') ? 'check' : 'write';

function assertNonEmptyString(value, field) {
	if (typeof value !== 'string' || value.trim() === '') {
		throw new Error(`Expected "${field}" to be a non-empty string.`);
	}
	return value;
}

function escapeTsString(value) {
	return value.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function escapeSwiftString(value) {
	return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

function renderSwiftStaticLet(name, value) {
	const escaped = escapeSwiftString(value);
	const indent = '    ';
	const continuationIndent = '        ';
	const singleLine = `${indent}public static let ${name} = "${escaped}"`;

	if (singleLine.length <= 140) {
		return singleLine;
	}

	return `${indent}public static let ${name} =\n${continuationIndent}"${escaped}"`;
}

function renderTs({ tagline, subtitle, description }) {
	return `// Generated by scripts/sync-marketing-copy.mjs from shared/marketingCopy.json.
// Do not edit this file manually.

export const MARKETING_COPY = {
\ttagline: '${escapeTsString(tagline)}',
\tsubtitle: '${escapeTsString(subtitle)}',
\tdescription: '${escapeTsString(description)}'
} as const;
`;
}

function renderSwift({ tagline, subtitle, description }) {
	return `// Generated by scripts/sync-marketing-copy.mjs from shared/marketingCopy.json.
// Do not edit this file manually.

import Foundation

/// Shared product marketing copy used across Apple surfaces.
public enum MarketingCopy {
${renderSwiftStaticLet('tagline', tagline)}
${renderSwiftStaticLet('subtitle', subtitle)}
${renderSwiftStaticLet('description', description)}
}
`;
}

async function syncFile(targetPath, expectedContents) {
	const existingContents = await readFile(targetPath, 'utf8');
	if (existingContents === expectedContents) {
		return true;
	}

	if (mode === 'check') {
		console.error(`Out of sync: ${path.relative(repoRoot, targetPath)}`);
		return false;
	}

	await writeFile(targetPath, expectedContents, 'utf8');
	console.log(`Updated ${path.relative(repoRoot, targetPath)}`);
	return true;
}

async function main() {
	const source = JSON.parse(await readFile(sourcePath, 'utf8'));
	const marketingCopy = {
		tagline: assertNonEmptyString(source.tagline, 'tagline'),
		subtitle: assertNonEmptyString(source.subtitle, 'subtitle'),
		description: assertNonEmptyString(source.description, 'description')
	};

	const tsContents = renderTs(marketingCopy);
	const swiftContents = renderSwift(marketingCopy);

	const results = await Promise.all([
		syncFile(tsPath, tsContents),
		syncFile(swiftPath, swiftContents)
	]);

	if (mode === 'check' && results.includes(false)) {
		console.error('Run `node scripts/sync-marketing-copy.mjs` to regenerate marketing copy adapters.');
		process.exitCode = 1;
	}
}

main().catch((error) => {
	console.error(error instanceof Error ? error.message : error);
	process.exitCode = 1;
});
